<?php

/*
|--------------------------------------------------------------------------
| Konfigurasi Database
|--------------------------------------------------------------------------
*/

$host = "localhost";
$username = "root";
$password = "";
$database = "humanresources";
$port = 3306;

/*
|--------------------------------------------------------------------------
| Membuat Koneksi MySQL
|--------------------------------------------------------------------------
*/

$conn = mysqli_connect(
    $host,
    $username,
    $password,
    $database,
    $port
);

/*
|--------------------------------------------------------------------------
| Memeriksa Koneksi
|--------------------------------------------------------------------------
*/

if (!$conn) {
    die(
        "Koneksi database gagal: "
        . mysqli_connect_error()
    );
}

/*
|--------------------------------------------------------------------------
| Mengatur Charset
|--------------------------------------------------------------------------
*/

if (!mysqli_set_charset($conn, "utf8mb4")) {
    die(
        "Gagal mengatur charset database: "
        . mysqli_error($conn)
    );
}

/*
|--------------------------------------------------------------------------
| Mengatur Zona Waktu Database
|--------------------------------------------------------------------------
*/

mysqli_query(
    $conn,
    "SET time_zone = '+07:00'"
);